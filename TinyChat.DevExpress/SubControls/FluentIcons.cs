	/// <summary>Gets the regular "Copy" icon drawn for <paramref name="pixelSize"/> device pixels.</summary>
	internal static SvgImage Copy(int pixelSize)
	{
		var size = GetDesignSize(pixelSize);
		return Create(_copyPaths[size], "Black", "#727272", size);
	}

	/// <summary>Gets "Copy" with the "A" of "Text Color" inside its front sheet, drawn for <paramref name="pixelSize"/> device pixels.</summary>
	internal static SvgImage CopyFormatted(int pixelSize)
	{
		var size = GetDesignSize(pixelSize);
		var (letterPath, transform) = _letterAPaths[size];
		return CreateSvg(
			$"<svg viewBox=\"0 0 {size} {size}\"><style type=\"text/css\">.Black{{fill:#727272;}}</style>" +
			$"<path d=\"{_copyPaths[size]}\" class=\"Black\" />" +
			$"<path d=\"{letterPath}\" transform=\"{transform}\" class=\"Black\" /></svg>");
	}

	/// <summary>Gets the regular "Arrow Undo" icon drawn for <paramref name="pixelSize"/> device pixels.</summary>
	internal static SvgImage Revert(int pixelSize)
	{
		var size = GetDesignSize(pixelSize);
		return Create(_arrowUndoPaths[size], "Black", "#727272", size);
	}

	/// <summary>
	/// Picks the Fluent design size that renders <paramref name="pixelSize"/> pixels without fractional scaling,
	/// for example 20 at 125 % and 24 at 150 %, and otherwise the closest one.
	/// </summary>
	internal static int GetDesignSize(int pixelSize)
	{
		int[] sizes = [24, 20, 16];
		foreach (var size in sizes)
		{
			if (pixelSize % size == 0)
				return size;
		}

		return sizes.MinBy(size => Math.Abs(size - pixelSize));
	}

	private static SvgImage Create(string pathData, string className, string color, int viewBoxSize = 16)
	{
		var svg = $"<svg viewBox=\"0 0 {viewBoxSize} {viewBoxSize}\"><style type=\"text/css\">.{className}{{fill:{color};}}</style><path d=\"{pathData}\" class=\"{className}\" /></svg>";
		return CreateSvg(svg);
	}

	private static SvgImage CreateSvg(string svg)
	{
		return SvgImage.FromStream(new MemoryStream(System.Text.Encoding.UTF8.GetBytes(svg)));
	}
